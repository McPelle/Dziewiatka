const SRODEK: [number, number] = [50.3, 19.5]; // domyślny środek (gdy brak miasta)

/** Odległość między miastami w km (haversine). Brak miasta → środek regionu. */
export function odlegloscMiast(a: string, b: string): number {
  const p = MIASTA[a] ?? SRODEK, q = MIASTA[b] ?? SRODEK;
  const R = 6371, rad = Math.PI / 180;
  const dLat = (q[0] - p[0]) * rad, dLon = (q[1] - p[1]) * rad;
  const s = Math.sin(dLat / 2) ** 2 + Math.cos(p[0] * rad) * Math.cos(q[0] * rad) * Math.sin(dLon / 2) ** 2;
  return Math.round(2 * R * Math.asin(Math.sqrt(s)));
}

/**
 * Realna odległość DROGOWA w km: dystans w linii prostej × współczynnik krętości dróg.
 * ~1.27 na nizinach (typowe nadłożenie tras w Polsce), ~1.42 gdy trasa prowadzi przez tereny górskie
 * (serpentyny, brak autostrad) — bliżej realnego czasu dojazdu niż odległość „w linii prostej".
 */
export function odlegloscDrogowa(a: string, b: string): number {
  const prosta = odlegloscMiast(a, b);
  const gory = gorskie(a) || gorskie(b);
  return Math.round(prosta * (gory ? 1.42 : 1.27));
}
