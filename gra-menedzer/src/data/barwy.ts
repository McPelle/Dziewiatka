/** Jasność koloru hex 0..1 (do doboru kontrastowego stroju wyjazdowego). */
function jasnosc(hex: string): number {
  const m = hex.replace("#", "");
  const n = m.length === 3 ? m.split("").map((c) => c + c).join("") : m;
  const r = parseInt(n.slice(0, 2), 16), g = parseInt(n.slice(2, 4), 16), b = parseInt(n.slice(4, 6), 16);
  return (0.299 * r + 0.587 * g + 0.114 * b) / 255;
}
/** Strój wyjazdowy: kontrast do domowego, z akcentem barwy klubu (ciemny granat lub biały). */
export function barwyWyjazdowe(nazwa: string): [string, string] {
  const [p] = barwyKlubu(nazwa);
  return jasnosc(p) > 0.6 ? ["#14213d", p] : ["#f2f2f2", p];
}
/** Czy dwa stroje kolorystycznie kolidują (zbyt podobna jasność i barwa). */
export function kolorKolizja(a: string, b: string): boolean {
  return Math.abs(jasnosc(a) - jasnosc(b)) < 0.2;
}

/** Barwy klubu: prawdziwe (słownik) → barwy pierwszego zespołu dla rezerw → z nazwy (słowa-kolory) → z hasza. */
/** Barwy klubów stworzonych przez gracza (rejestrowane przy tworzeniu i wczytaniu zapisu). */
export const BARWY_WLASNE: Record<string, [string, string]> = {};
export function barwyKlubu(nazwa: string): [string, string] {
  if (BARWY_WLASNE[nazwa]) return BARWY_WLASNE[nazwa];
  const wpis = BARWY_KLUBOW[nazwa];
  if (wpis) return wpis;
  // Rezerwy („X II", „X III", „X 2") dziedziczą barwy pierwszego zespołu.
  const bezRezerw = nazwa.replace(/\s+(II|III|IV|2)\b/g, "").replace(/\s+/g, " ").trim();
  if (bezRezerw !== nazwa && BARWY_KLUBOW[bezRezerw]) return BARWY_KLUBOW[bezRezerw];
  for (const [re, para] of SLOWA_BARW) if (re.test(nazwa)) return para;
  let h = 0;
  for (const c of nazwa) h = (h * 31 + c.charCodeAt(0)) >>> 0;
  return PALETA[h % PALETA.length];
}
